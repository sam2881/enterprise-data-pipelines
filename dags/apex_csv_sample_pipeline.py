with DAG(
    dag_id=DAG_ID,
    default_args=default_args,
    description="APEX CSV Sample Pipeline - Medallion Architecture (Landing → Bronze → Silver → Gold → BigQuery)",
    schedule="@daily",
    start_date=datetime(2026, 2, 7),
    catchup=False,
    max_active_runs=1,
    tags=["apex", "csv", "medallion", "sample", "gcs", "bigquery"],
) as dag:

    t_init = PythonOperator(
        task_id="init_execution",
        python_callable=init_execution,
    )

    t_landing = PythonOperator(
        task_id="create_sample_csv_landing",
        python_callable=create_sample_csv,
    )

    t_bronze = PythonOperator(
        task_id="landing_to_bronze",
        python_callable=landing_to_bronze,
    )

    t_silver = PythonOperator(
        task_id="bronze_to_silver",
        python_callable=bronze_to_silver,
    )

    t_gold = PythonOperator(
        task_id="silver_to_gold",
        python_callable=silver_to_gold,
    )

    t_bq = PythonOperator(
        task_id="load_to_bigquery",
        python_callable=load_to_bigquery,
    )

    t_finalize = PythonOperator(
        task_id="finalize_execution",
        python_callable=finalize_execution,
        trigger_rule=TriggerRule.ALL_SUCCESS,
    )

    # Task dependencies: Medallion flow
    t_init >> t_landing >> t_bronze >> t_silver >> t_gold >> t_bq >> t_finalize
