def init_execution(**context):
    """Initialize execution context and create batch_id."""
    import uuid

    batch_id = context["ds_nodash"]
    run_id = str(uuid.uuid4())[:8]

    execution_context = {
        "feed_id": FEED_ID,
        "batch_id": batch_id,
        "run_id": run_id,
        "dag_id": DAG_ID,
        "start_time": datetime.utcnow().isoformat(),
        "zones_completed": [],
    }

    logger.info(f"[APEX] Initialized execution: feed={FEED_ID} batch={batch_id} run={run_id}")
    context["ti"].xcom_push(key="execution_context", value=json.dumps(execution_context))
    return execution_context


